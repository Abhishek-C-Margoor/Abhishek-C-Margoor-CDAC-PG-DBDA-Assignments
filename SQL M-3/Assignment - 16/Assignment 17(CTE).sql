USE HR;

-- 1) HELLO, EMPLOYEES (STAGING CTE)
-- TASK: BUILD A CTE THAT RETURNS EMPLOYEE_ID, FULL_NAME, JOB_ID, DEPARTMENT_ID, SALARY.
--  OUTPUT: EMPLOYEE_ID, FULL_NAME, JOB_ID, DEPARTMENT_ID, SALARY.
--  HINT: CONCAT(COALESCE(FIRST_NAME,''),' ',LAST_NAME).

WITH CTE1 AS (
	SELECT EMPLOYEE_ID, CONCAT(COALESCE(FIRST_NAME ," ")," ",LAST_NAME) AS FULL_NAME, JOB_ID, DEPARTMENT_ID, SALARY FROM EMPLOYEES
)
SELECT FULL_NAME , JOB_ID , DEPARTMENT_ID,SALARY FROM CTE1;

-- 2) DEPARTMENT HEADCOUNT (INCLUDE 0)
-- TASK: CTE WITH EMPLOYEES GROUPED BY DEPARTMENT_ID. LEFT-JOIN TO DEPARTMENTS TO SHOW ALL DEPARTMENTS.
--  OUTPUT: DEPARTMENT_ID, DEPARTMENT_NAME, HEADCOUNT.
--  HINT: COALESCE(HEADCOUNT,0).
WITH CTE2 AS (
SELECT DEPARTMENT_ID,COUNT(*) AS HEADCOUNT FROM EMPLOYEES GROUP BY DEPARTMENT_ID
)
SELECT D.DEPARTMENT_NAME , D.DEPARTMENT_ID , COALESCE(C.HEADCOUNT,0) 
FROM DEPARTMENTS D 
LEFT JOIN CTE2 C
USING(DEPARTMENT_ID);



-- 3) AVG SALARY BY JOB
-- TASK: CTE AGGREGATES AVERAGE SALARY PER JOB_ID; JOIN TO JOBS FOR TITLES.
--  OUTPUT: JOB_ID, JOB_TITLE, EMP_COUNT, AVG_SALARY.
--  HINT: ROUND(AVG(SALARY),2).

WITH CTEA AS(
	SELECT COUNT(EMPLOYEE_ID) AS EMP_COUNT , ROUND(AVG(SALARY),2) AS AVG_SALARY,JOB_ID
    FROM EMPLOYEES
    GROUP BY JOB_ID
)
SELECT J.JOB_ID,J.JOB_TITLE,C.EMP_COUNT,C.AVG_SALARY
FROM JOBS J
JOIN CTEA C 
USING (JOB_ID);


-- 4) EMPLOYEE → MANAGER (1 HOP)
-- TASK: STAGE EMPLOYEES IN A CTE; SELF-JOIN TO GET DIRECT MANAGER NAME.
--  OUTPUT: EMPLOYEE_ID, EMPLOYEE_NAME, MANAGER_ID, MANAGER_NAME.
--  HINT: LEFT JOIN; TOP BOSS MAY HAVE MANAGER_ID = 0 OR NULL.
SELECT * FROM EMPLOYEES;
WITH CTEB AS (
	SELECT CONCAT(FIRST_NAME," ",LAST_NAME) AS MANAGER_NAME,MANAGER_ID
    FROM EMPLOYEES
    GROUP BY MANAGER_ID
)
SELECT E.EMPLOYEE_ID ,CONCAT(E.FIRST_NAME,E.LAST_NAME) AS EMPLOYEE_NAME, B.MANAGER_NAME,B.MANAGER_ID
FROM EMPLOYEES E
JOIN CTEB B
GROUP BY B.MANAGER_ID;
  


-- 5) EMPLOYEES WITHOUT A DEPARTMENT
-- TASK: USE A CTE TO LIST EMPLOYEES WHERE DEPARTMENT_ID IS NULL OR DEPARTMENT_ID=0.
--  OUTPUT: EMPLOYEE_ID, FULL_NAME, JOB_ID, DEPARTMENT_ID.
WITH CTE5 AS (
	SELECT DEPARTMENT_ID ,CONCAT(FIRST_NAME,"",LAST_NAME)AS NAAM
    FROM EMPLOYEES 
    WHERE DEPARTMENT_ID IS NULL OR DEPARTMENT_ID = 0
    GROUP BY DEPARTMENT_ID , NAAM
)
	
SELECT C.* , E.JOB_ID,E.EMPLOYEE_ID
FROM EMPLOYEES E
JOIN CTE5 C
USING (DEPARTMENT_ID);


-- 6) DEPARTMENTS WITHOUT EMPLOYEES
-- TASK: DISTINCT DEPARTMENT_ID FROM EMPLOYEES IN A CTE; ANTI-JOIN TO DEPARTMENTS.
--  OUTPUT: DEPARTMENT_ID, DEPARTMENT_NAME.

WITH CTE6 AS(
	SELECT DISTINCT DEPARTMENT_ID FROM EMPLOYEES
)
SELECT D.DEPARTMENT_NAME , C.DEPARTMENT_ID 
FROM DEPARTMENTS D 
LEFT JOIN CTE6 C
ON D.DEPARTMENT_ID = C.DEPARTMENT_ID
WHERE C.DEPARTMENT_ID IS NULL;

-- 7) MAP EMPLOYEES TO REGION (CLEAN TEXT)
-- TASK: CTE JOINS EMPLOYEES → DEPARTMENTS → LOCATIONS → COUNTRIES → REGIONS AND TRIMS REGION_NAME.
--  OUTPUT: EMPLOYEE_ID, FULL_NAME, DEPARTMENT_NAME, CITY, COUNTRY_NAME, REGION_NAME.
--  HINT: TRIM(REPLACE(REGION_NAME,'\R','')).

WITH CTE7 AS (
	SELECT E.EMPLOYEE_ID , CONCAT(E.FIRST_NAME,"",E.LAST_NAME) AS FULL_NAME , D.DEPARTMENT_NAME,L.CITY,C.COUNTRY_NAME,TRIM(REPLACE(R.REGION_NAME,'\R','')) AS REGION_NAME
    FROM EMPLOYEES E
    JOIN DEPARTMENTS D
    USING(DEPARTMENT_ID)
    JOIN LOCATIONS L
    USING(LOCATION_ID)
    JOIN COUNTRIES C 
    USING(COUNTRY_ID) 
    JOIN REGIONS R 
    USING(REGION_ID)
)

SELECT EMPLOYEE_ID, FULL_NAME, DEPARTMENT_NAME, CITY, COUNTRY_NAME, REGION_NAME
FROM CTE7;


-- 8) SIMPLE PAY-BAND CHECK
-- TASK: CTE JOINS EMPLOYEES TO JOBS; RETURN ROWS WHERE SALARY < MIN_SALARY OR SALARY > MAX_SALARY.
--  OUTPUT: EMPLOYEE_ID, FULL_NAME, JOB_TITLE, SALARY, MIN_SALARY, MAX_SALARY.

WITH CTE8 AS (
	SELECT EMPLOYEE_ID ,  CONCAT(E.FIRST_NAME,"",E.LAST_NAME) AS FULL_NAME ,JOB_TITLE ,SALARY,MIN_SALARY,MAX_SALARY
    WHERE SALARY < MIN_SALARY OR SALARY > MAX_SALARY
)

SELECT EMPLOYEE_ID, FULL_NAME, JOB_TITLE, SALARY, MIN_SALARY, MAX_SALARY
FROM CTE8
GROUP BY JOB_ID;

-- 9) TOP EARNERS (OVERALL)
-- TASK: CTE SELECTING EMPLOYEE_ID, FULL_NAME, SALARY, THEN ORDER AND LIMIT TO TOP 5.
--  OUTPUT: EMPLOYEE_ID, FULL_NAME, SALARY.
--  HINT: USE THE CTE JUST TO KEEP THE FINAL SELECT CLEAN.

WITH CTE9 AS (
SELECT DISTINCT EMPLOYEE_ID ,CONCAT(FIRST_NAME,"",LAST_NAME) AS FULL_NAME,SALARY
FROM EMPLOYEES 
ORDER BY SALARY DESC
LIMIT 5
)
SELECT EMPLOYEE_ID, FULL_NAME, SALARY 
FROM CTE9;

