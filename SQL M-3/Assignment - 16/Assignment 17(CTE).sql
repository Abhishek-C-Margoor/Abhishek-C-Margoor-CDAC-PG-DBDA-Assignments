-- 10) JOBS PRESENT IN EACH DEPARTMENT
-- TASK: CTE GROUPS EMPLOYEES BY DEPARTMENT_ID, JOB_ID AND COUNTS. JOIN JOBS FOR TITLE.
--  OUTPUT: DEPARTMENT_NAME, JOB_TITLE, EMPLOYEES_IN_ROLE.

WITH CTE10 AS (
    SELECT DEPARTMENT_ID, JOB_ID, COUNT(*) AS EMPLOYEES_IN_ROLE
    FROM EMPLOYEES
    GROUP BY DEPARTMENT_ID, JOB_ID
)
SELECT D.DEPARTMENT_NAME,
       J.JOB_TITLE,
       C.EMPLOYEES_IN_ROLE
FROM CTE10 C
JOIN DEPARTMENTS D 
USING(DEPARTMENT_ID)
JOIN JOBS J 
USING(JOB_ID)
ORDER BY D.DEPARTMENT_NAME, J.JOB_TITLE;




-- 11) HEADCOUNT BY REGION
-- TASK: REUSE THE “MAP TO REGION” IDEA IN A CTE; THEN GROUP BY REGION.
--  OUTPUT: REGION_NAME, HEADCOUNT.
--  HINT: HANDLE NULL REGION AS “UNKNOWN”.

WITH CTE11 AS (
 SELECT COUNT(E.EMPLOYEE_ID) AS HEADCOUNT ,COALESCE(r.region_name, 'UNKNOWN') AS REGION_NAME
    FROM EMPLOYEES E
    LEFT JOIN DEPARTMENTS D
    USING(DEPARTMENT_ID)
    LEFT JOIN LOCATIONS L
    USING(LOCATION_ID)
    LEFT JOIN COUNTRIES C 
    USING(COUNTRY_ID) 
    LEFT JOIN REGIONS R 
    USING(REGION_ID)
    group by R.REGION_ID
)

SELECT  HEADCOUNT , REGION_NAME
FROM CTE11;

-- 12) COMMISSION SNAPSHOT
-- TASK: IN A CTE, COMPUTE A FLAG HAS_COMMISSION = COMMISSION_PCT > 0. THEN COUNT BY FLAG.
--  OUTPUT: HAS_COMMISSION, HEADCOUNT.
--  OPTIONAL: BREAK DOWN BY DEPARTMENT AS WELL.

WITH CTE12 AS (
SELECT COUNT(EMPLOYEE_ID) AS HEADCOUNT , 
	CASE 
		WHEN COMMISSION_PCT >0 THEN "LOW"
        WHEN COMMISSION_PCT <0 THEN "HIGH"
	END AS HAS_COMMISSION
FROM EMPLOYEES 
group by EMPLOYEE_ID
)
SELECT HEAD_COUNT,HAS_COMMISSION FROM CTE12;


-- 13) EMPLOYEES WITH ANY JOB HISTORY
-- TASK: CTE WITH DISTINCT EMPLOYEE_ID FROM JOB_HISTORY (EXCLUDE DUMMY ROW). JOIN TO EMPLOYEES.
--  OUTPUT: EMPLOYEE_ID, FULL_NAME, HISTORY_ROW_COUNT.
--  HINT: COUNT(*) OVER (PARTITION BY EMPLOYEE_ID) OR AGGREGATE BEFORE JOIN.
SELECT * FROM JOB_HISTORY;

WITH CTE13 AS (
	SELECT DISTINCT EMPLOYEE_ID ,COUNT(*) AS HISTORY_ROW_COUNT
    FROM JOB_HISTORY
    GROUP BY EMPLOYEE_ID
)

SELECT E.EMPLOYEE_ID,CONCAT(E.FIRST_NAME,"",E.LAST_NAME) AS FULL_NAME,C.HISTORY_ROW_COUNT 
FROM EMPLOYEES E
JOIN CTE13 C
USING(EMPLOYEE_ID)
WHERE E.EMPLOYEE_ID IS NOT null;

-- 14) LATEST HISTORY ROW (GENTLE)
-- TASK: CLEAN JOB_HISTORY IN A CTE (EXCLUDE ZERO/INVALID DATES) AND PICK THE LATEST ROW PER EMPLOYEE USING ROW_NUMBER.
--  OUTPUT: EMPLOYEE_ID, LAST_HIST_JOB_ID, LAST_HIST_DEPARTMENT_ID, LAST_HIST_END_DATE.
--  HINT: ORDER BY END_DATE DESC, START_DATE DESC.

WITH CTE14 AS (
SELECT E.EMPLOYEE_ID , J.JOB_ID AS LAST_HIST_JOB_ID, J.DEPARTMENT_ID AS LAST_HIST_DEPARTMENT_ID,J.END_DATE AS LAST_HIST_END_DATE
FROM EMPLOYEES E
JOIN JOB_HISTORY J 
USING(EMPLOYEE_ID)
ORDER BY END_DATE DESC, START_DATE DESC
)

SELECT EMPLOYEE_ID,LAST_HIST_JOB_ID, LAST_HIST_DEPARTMENT_ID, LAST_HIST_END_DATE
FROM CTE14;


-- 15) LOCATIONS PER COUNTRY
-- TASK: CTE GROUPS LOCATIONS BY COUNTRY_ID; JOIN TO COUNTRIES.
--  OUTPUT: COUNTRY_ID, COUNTRY_NAME, LOCATION_COUNT.
--  HINT: COALESCE(COUNTRY_NAME,'UNKNOWN').

WITH CTE15 AS (
SELECT COUNTRY_ID,COALESCE(COUNTRY_NAME,'UNKNOWN') AS COUNTRY_NAME,count(*) AS LOCATION_COUNT
FROM LOCATIONS L
JOIN COUNTRIES C 
USING(COUNTRY_ID)
group by COUNTRY_ID
)
SELECT COUNTRY_ID, COUNTRY_NAME, LOCATION_COUNT
FROM CTE15;

